// Assembles scraped SCG (Summa Contra Gentiles) text + per-book audio manifests into
// app/data-scg.js for the reader app. Mirrors build-data.cjs but for SCG's simpler
// Book -> Chapter structure (no "articles"). Works incrementally: safe to run with
// only some books' audio manifests present (e.g. while Books 3-4 TTS is still being
// generated) — chapters with no matching audio track simply get hasAudio:false.
// Usage: node build-data-scg.cjs

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const TEXT_DIR = path.join(ROOT, 'data', 'text');
const AUDIO_DIR = path.join(ROOT, 'audio');
const OUT_FILE = path.join(ROOT, 'app', 'data-scg.js');

const BOOK_ROMAN = { 1: 'I', 2: 'II', 3: 'III', 4: 'IV' };

function loadBookText(book) {
  const file = path.join(TEXT_DIR, `scg_book${book}.json`);
  if (!fs.existsSync(file)) return null;
  try {
    return JSON.parse(fs.readFileSync(file, 'utf-8'));
  } catch (e) {
    console.error(`Failed to parse ${file}: ${e.message}`);
    return null;
  }
}

function loadAudioManifest(book) {
  const manifestPath = path.join(AUDIO_DIR, `scg_book${book}`, 'manifest.json');
  if (!fs.existsSync(manifestPath)) return null;
  try {
    return JSON.parse(fs.readFileSync(manifestPath, 'utf-8'));
  } catch (e) {
    console.error(`Failed to parse manifest for scg_book${book}: ${e.message}`);
    return null;
  }
}

function main() {
  const textIndex = {}; // "B{book}C{chapter}" -> chapter object (+ audio fields)
  const books = [];
  var totalChapters = 0;
  var chaptersWithAudio = 0;

  for (let book = 1; book <= 4; book++) {
    const chapters = loadBookText(book);
    if (!chapters || !chapters.length) {
      books.push({ book, bookTitle: null, roman: BOOK_ROMAN[book], chapters: [], hasAnyText: false });
      continue;
    }

    const manifest = loadAudioManifest(book);
    // Audio tracks are numbered sequentially and correspond 1:1 to chapter numbers
    // (verified against LibriVox track titles, which carry the same roman-numeral
    // chapter markers as the text). Track N supplies audio for chapter N.
    const trackByNumber = {};
    if (manifest && Array.isArray(manifest.tracks)) {
      manifest.tracks.forEach((t) => { trackByNumber[t.track] = t; });
    }

    const sortedChapters = chapters.slice().sort((a, b) => a.chapter - b.chapter);
    const bookTitle = sortedChapters[0].bookTitle || `Book ${BOOK_ROMAN[book]}`;

    const chapterList = sortedChapters.map((c) => {
      const track = trackByNumber[c.chapter] || null;
      const key = `B${book}C${c.chapter}`;
      const entry = {
        book,
        chapter: c.chapter,
        title: c.title,
        paragraphs: c.paragraphs,
        hasAudio: !!track,
        // 'SCG-' prefix keeps this in its own AUDIO_URLS namespace: scgKey()
        // and metaKey() both produce plain "B{book}C{chapter}" (they're
        // literally the same format), so an unprefixed key here would
        // collide with Metaphysics' identical-looking chapter keys in the
        // single flat AUDIO_URLS map.
        audioFile: track ? `SCG-${key}` : null,
        durationSeconds: track ? track.durationSeconds : null,
      };
      textIndex[key] = entry;
      totalChapters++;
      if (track) chaptersWithAudio++;
      return {
        chapter: c.chapter,
        title: c.title,
        hasAudio: !!track,
      };
    });

    books.push({
      book,
      bookTitle,
      roman: BOOK_ROMAN[book],
      hasAnyText: true,
      chapters: chapterList,
    });
  }

  const out = [];
  out.push('// Auto-generated by scripts/build-data-scg.cjs — do not edit by hand.');
  out.push(`window.SCG_BOOKS = ${JSON.stringify(books, null, 2)};`);
  out.push(`window.SCG_TEXT = ${JSON.stringify(textIndex, null, 2)};`);
  fs.writeFileSync(OUT_FILE, out.join('\n'), 'utf-8');

  console.log(`Wrote ${OUT_FILE}`);
  console.log(`  Chapters loaded: ${totalChapters}`);
  console.log(`  Chapters with audio: ${chaptersWithAudio}/${totalChapters}`);
  books.forEach((b) => {
    if (!b.hasAnyText) { console.log(`  Book ${b.book}: no text yet`); return; }
    const withAudio = b.chapters.filter((c) => c.hasAudio).length;
    console.log(`  Book ${b.book} (${b.bookTitle}): ${b.chapters.length} chapters, ${withAudio} with audio`);
  });
}

main();
