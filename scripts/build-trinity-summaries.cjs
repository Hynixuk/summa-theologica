#!/usr/bin/env node
/**
 * build-trinity-summaries.cjs
 *
 * Adds window.SUMMARIES.trinity = { chapters: {...} } to app/data-summaries.js,
 * and builds app/data-trinity-summaries.js (window.TRINITY_SUMMARIES = { overview, books })
 * in the same shape as app/data-metaphysics-summaries.js.
 *
 * Sources:
 * - data/summaries/trinity-chapters-complete.json  (flat "TRIN-B{book}C{chapter}" -> one-sentence summary)
 * - data/trinity-summaries.json                    ({ overview: {title, content}, books: [{book, title, summary}, ...] })
 *
 * This script only ADDS/UPDATES the `trinity` key of window.SUMMARIES; it preserves
 * the existing st/scg/metaphysics content already present in app/data-summaries.js
 * verbatim (it does not re-derive them from their own source files the way
 * build-summaries.cjs does).
 *
 * Usage: node scripts/build-trinity-summaries.cjs
 */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'data');
const APP = path.join(ROOT, 'app');

const SUMMARIES_OUT = path.join(APP, 'data-summaries.js');
const TRINITY_SUMMARIES_OUT = path.join(APP, 'data-trinity-summaries.js');

function loadJSON(filePath) {
  if (!fs.existsSync(filePath)) return null;
  return JSON.parse(fs.readFileSync(filePath, 'utf-8'));
}

// Loads the existing window.SUMMARIES object out of app/data-summaries.js by
// evaluating the file in a sandboxed context (rather than re-deriving st/scg/
// metaphysics from their own source files, which is build-summaries.cjs's job).
function loadExistingSummaries() {
  if (!fs.existsSync(SUMMARIES_OUT)) return {};
  const code = fs.readFileSync(SUMMARIES_OUT, 'utf-8');
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  vm.runInContext(code, sandbox, { filename: SUMMARIES_OUT });
  return sandbox.window.SUMMARIES || {};
}

function main() {
  const trinityChapters = loadJSON(path.join(DATA, 'summaries', 'trinity-chapters-complete.json')) || {};
  const trinityBookLevel = loadJSON(path.join(DATA, 'trinity-summaries.json')) || { overview: null, books: [] };

  console.log(`Trinity chapter summaries: ${Object.keys(trinityChapters).length}`);
  console.log(`Trinity book summaries: ${trinityBookLevel.books.length}`);

  // 1. Update app/data-summaries.js: add/replace window.SUMMARIES.trinity, keep the rest untouched.
  const summaries = loadExistingSummaries();
  summaries.trinity = { chapters: trinityChapters };

  const summariesOutput =
    '// Auto-generated by scripts/build-summaries.cjs (st/scg/metaphysics) and\n' +
    '// scripts/build-trinity-summaries.cjs (trinity) — do not edit by hand.\n' +
    '// Rebuild st/scg/metaphysics with: node scripts/build-summaries.cjs\n' +
    '// Rebuild trinity with: node scripts/build-trinity-summaries.cjs\n' +
    'window.SUMMARIES = ' + JSON.stringify(summaries, null, 2) + ';\n';
  fs.writeFileSync(SUMMARIES_OUT, summariesOutput, 'utf-8');
  console.log(`Wrote ${SUMMARIES_OUT}`);

  // 2. Write app/data-trinity-summaries.js in the same shape as data-metaphysics-summaries.js
  const trinitySummariesOutput =
    '// Auto-generated by scripts/build-trinity-summaries.cjs — do not edit by hand.\n' +
    '// Book summaries and overview for St. Augustine\'s On the Trinity\n' +
    'window.TRINITY_SUMMARIES = ' + JSON.stringify(trinityBookLevel, null, 2) + ';\n';
  fs.writeFileSync(TRINITY_SUMMARIES_OUT, trinitySummariesOutput, 'utf-8');
  console.log(`Wrote ${TRINITY_SUMMARIES_OUT}`);
}

main();
