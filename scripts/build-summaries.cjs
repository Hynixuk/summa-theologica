#!/usr/bin/env node
/**
 * build-summaries.cjs
 *
 * Builds app/data-summaries.js by merging all three summary JSON files:
 * - data/st-summaries.json (Summa Theologiae summaries)
 * - data/scg-summaries.json (Summa Contra Gentiles summaries)
 * - data/metaphysics-summaries.json (Aristotle's Metaphysics summaries)
 *
 * Output: window.SUMMARIES = { st: {...}, scg: {...}, metaphysics: {...} }
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ST_FILE = path.join(ROOT, 'data', 'st-summaries.json');
const SCG_FILE = path.join(ROOT, 'data', 'scg-summaries.json');
const METAPHYSICS_FILE = path.join(ROOT, 'data', 'metaphysics-summaries.json');
const OUT_FILE = path.join(ROOT, 'app', 'data-summaries.js');

function loadJSON(filePath) {
  if (!fs.existsSync(filePath)) {
    console.warn(`Warning: ${filePath} not found`);
    return null;
  }
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf-8'));
  } catch (e) {
    console.error(`Error parsing ${filePath}: ${e.message}`);
    return null;
  }
}

function main() {
  console.log('Loading summary files...');

  const stSummaries = loadJSON(ST_FILE);
  const scgSummaries = loadJSON(SCG_FILE);
  const metaphysicsSummaries = loadJSON(METAPHYSICS_FILE);

  const summaries = {};
  let loadedCount = 0;

  if (stSummaries) {
    summaries.st = stSummaries;
    loadedCount++;
    console.log('✓ Loaded ST (Summa Theologiae) summaries');
  } else {
    console.log('✗ ST summaries not loaded');
  }

  if (scgSummaries) {
    summaries.scg = scgSummaries;
    loadedCount++;
    console.log('✓ Loaded SCG (Summa Contra Gentiles) summaries');
  } else {
    console.log('✗ SCG summaries not loaded');
  }

  if (metaphysicsSummaries) {
    summaries.metaphysics = metaphysicsSummaries;
    loadedCount++;
    console.log('✓ Loaded Metaphysics summaries');
  } else {
    console.log('✗ Metaphysics summaries not loaded');
  }

  if (loadedCount === 0) {
    console.error('Error: No summary files loaded. Aborting.');
    process.exit(1);
  }

  // Build the output file
  const output = [];
  output.push('// Auto-generated by scripts/build-summaries.cjs — do not edit by hand.');
  output.push('// Combines ST, SCG, and Metaphysics summaries');
  output.push('');
  output.push(`window.SUMMARIES = ${JSON.stringify(summaries, null, 2)};`);
  output.push('');

  // Ensure output directory exists
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });

  // Write the file
  fs.writeFileSync(OUT_FILE, output.join('\n'), 'utf-8');

  console.log('');
  console.log(`✓ Successfully wrote ${OUT_FILE}`);
  console.log(`  - ST parts: ${summaries.st ? Object.keys(summaries.st.parts).length : 0}`);
  console.log(`  - SCG books: ${summaries.scg ? Object.keys(summaries.scg.books).length : 0}`);
  console.log(`  - Metaphysics books: ${summaries.metaphysics ? summaries.metaphysics.books.length : 0}`);

  // Validate the output file can be parsed
  try {
    const fileContent = fs.readFileSync(OUT_FILE, 'utf-8');
    // Check that it's valid JavaScript by looking for the assignment
    if (fileContent.includes('window.SUMMARIES = {')) {
      console.log('✓ Output file structure validated');
    }
  } catch (e) {
    console.error(`Error validating output: ${e.message}`);
    process.exit(1);
  }
}

main();
