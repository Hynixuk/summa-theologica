// Assembles scraped "On the Trinity" (De Trinitate) text + per-book audio
// manifests into app/data-trinity.js for the reader app. Mirrors
// build-data-scg.cjs but for Trinity's 15-book Book -> Chapter structure
// (no "articles"), including a "chapter 0" (Introduction/Preface) for the
// books that have one. Works incrementally: safe to run with only some
// books' audio manifests present — chapters with no matching audio track
// simply get hasAudio:false.
// Usage: node build-data-trinity.cjs

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const TEXT_DIR = path.join(ROOT, 'data', 'text');
const AUDIO_DIR = path.join(ROOT, 'audio');
const OUT_FILE = path.join(ROOT, 'app', 'data-trinity.js');

const BOOK_ROMAN = { 1: 'I', 2: 'II', 3: 'III', 4: 'IV', 5: 'V', 6: 'VI', 7: 'VII', 8: 'VIII', 9: 'IX', 10: 'X', 11: 'XI', 12: 'XII', 13: 'XIII', 14: 'XIV', 15: 'XV' };

function loadBookText(book) {
  const file = path.join(TEXT_DIR, `trinity_book${book}.json`);
  if (!fs.existsSync(file)) return null;
  try {
    return JSON.parse(fs.readFileSync(file, 'utf-8'));
  } catch (e) {
    console.error(`Failed to parse ${file}: ${e.message}`);
    return null;
  }
}

function loadAudioManifest(book) {
  const n = String(book).padStart(2, '0');
  const manifestPath = path.join(AUDIO_DIR, `trinity_book${n}`, 'manifest.json');
  if (!fs.existsSync(manifestPath)) return null;
  try {
    return JSON.parse(fs.readFileSync(manifestPath, 'utf-8'));
  } catch (e) {
    console.error(`Failed to parse manifest for trinity_book${n}: ${e.message}`);
    return null;
  }
}

function main() {
  const textIndex = {}; // "TRIN-B{book}C{chapter}" -> chapter object (+ audio fields)
  const books = [];
  var totalChapters = 0;
  var chaptersWithAudio = 0;

  for (let book = 1; book <= 15; book++) {
    const chapters = loadBookText(book);
    if (!chapters || !chapters.length) {
      books.push({ book, bookTitle: null, roman: BOOK_ROMAN[book], chapters: [], hasAnyText: false });
      continue;
    }

    const manifest = loadAudioManifest(book);
    // Audio tracks are generated 1:1 with chapter numbers by
    // generate-trinity-tts.cjs (including chapter 0, the Introduction/
    // Preface, where present) so track N supplies audio for chapter N.
    const trackByNumber = {};
    if (manifest && Array.isArray(manifest.tracks)) {
      manifest.tracks.forEach((t) => { trackByNumber[t.track] = t; });
    }

    const sortedChapters = chapters.slice().sort((a, b) => a.chapter - b.chapter);
    const bookTitle = sortedChapters[0].bookTitle || `On the Trinity (Book ${BOOK_ROMAN[book]})`;

    const chapterList = sortedChapters.map((c) => {
      const track = trackByNumber[c.chapter] || null;
      // 'TRIN-' prefix keeps this in its own AUDIO_URLS namespace: SCG and
      // Metaphysics both produce plain "B{book}C{chapter}" keys and already
      // collide with each other there (SCG works around this with its own
      // 'SCG-' prefix, see build-data-scg.cjs) — use the same trick here so
      // Trinity's book/chapter numbers never collide with either.
      const key = `TRIN-B${book}C${c.chapter}`;
      const entry = {
        book,
        chapter: c.chapter,
        title: c.title,
        paragraphs: c.paragraphs,
        hasAudio: !!track,
        audioFile: track ? key : null,
        durationSeconds: track ? track.durationSeconds : null,
      };
      textIndex[key] = entry;
      totalChapters++;
      if (track) chaptersWithAudio++;
      return {
        chapter: c.chapter,
        title: c.title,
        hasAudio: !!track,
        audioTrack: c.chapter,
      };
    });

    books.push({
      book,
      bookTitle,
      roman: BOOK_ROMAN[book],
      hasAnyText: true,
      chapters: chapterList,
    });
  }

  const out = [];
  out.push('// Auto-generated by scripts/build-data-trinity.cjs — do not edit by hand.');
  out.push(`window.TRINITY_BOOKS = ${JSON.stringify(books, null, 2)};`);
  out.push(`window.TRINITY_TEXT = ${JSON.stringify(textIndex, null, 2)};`);
  fs.writeFileSync(OUT_FILE, out.join('\n'), 'utf-8');

  console.log(`Wrote ${OUT_FILE}`);
  console.log(`  Chapters loaded: ${totalChapters}`);
  console.log(`  Chapters with audio: ${chaptersWithAudio}/${totalChapters}`);
  books.forEach((b) => {
    if (!b.hasAnyText) { console.log(`  Book ${b.book}: no text yet`); return; }
    const withAudio = b.chapters.filter((c) => c.hasAudio).length;
    console.log(`  Book ${b.book} (${b.bookTitle}): ${b.chapters.length} chapters, ${withAudio} with audio`);
  });
}

main();
