// Merges Trinity ("TRIN-B{book}C{chapter}") entries into the EXISTING
// app/audio-urls.js in place, without touching any other work's keys.
//
// Why not just run build-audio-urls.cjs? That script rebuilds the whole
// file from scratch and requires every work's local audio/*/manifest.json
// to be present (ST/SCG/Metaphysics) to reproduce their sections — but this
// worktree only ever had Trinity's audio generated locally (audio/ is
// gitignored, so the other works' local manifests never existed here). This
// script instead reads the current committed audio-urls.js (which already
// has correct ST/SCG/META entries) and adds only the new TRIN-* keys,
// verified against real uploaded GitHub Releases assets exactly the same
// way build-audio-urls.cjs's SCG section does.
//
// Usage: node merge-trinity-audio-urls.cjs <assets.json> [<assets.json> ...]
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const AUDIO_DIR = path.join(ROOT, 'audio');
const OUT_FILE = path.join(ROOT, 'app', 'audio-urls.js');

const assetFiles = process.argv.slice(2);
if (!assetFiles.length) {
  console.error('Usage: node merge-trinity-audio-urls.cjs <assets.json> [<assets.json> ...]');
  process.exit(1);
}

function githubSanitize(name) {
  return name.replace(/[^A-Za-z0-9-]+/g, '.');
}

const assetByName = new Map();
for (const f of assetFiles) {
  const list = JSON.parse(fs.readFileSync(f, 'utf-8'));
  list.forEach((a) => {
    if (!assetByName.has(a.name)) assetByName.set(a.name, a.url);
  });
}
console.log(`Loaded ${assetByName.size} unique uploaded asset names from ${assetFiles.length} listing(s).`);

function resolveLocalFile(relPathFromAudioDir, missingList) {
  const localName = path.basename(relPathFromAudioDir);
  const sanitized = githubSanitize(localName);
  const url = assetByName.get(sanitized);
  if (!url) { missingList.push(relPathFromAudioDir); return null; }
  return url;
}

// Load existing map
const existingSrc = fs.readFileSync(OUT_FILE, 'utf-8');
const existingMatch = existingSrc.match(/window\.AUDIO_URLS\s*=\s*(\{[\s\S]*\});?\s*$/);
if (!existingMatch) throw new Error('Could not find window.AUDIO_URLS in ' + OUT_FILE);
const audioMap = JSON.parse(existingMatch[1]);
const beforeCount = Object.keys(audioMap).length;

let matched = 0;
const missingList = [];

for (let book = 1; book <= 15; book++) {
  const n = String(book).padStart(2, '0');
  const manifestPath = path.join(AUDIO_DIR, `trinity_book${n}`, 'manifest.json');
  if (!fs.existsSync(manifestPath)) continue;
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf-8'));
  manifest.tracks.forEach((t) => {
    const url = resolveLocalFile(path.join(`trinity_book${n}`, t.file), missingList);
    if (!url) return;
    audioMap[`TRIN-B${book}C${t.track}`] = url;
    matched++;
  });
}

console.log(`Matched ${matched} local Trinity files to real uploaded URLs.`);
if (missingList.length) {
  console.log(`⚠ ${missingList.length} local Trinity files had no matching uploaded asset yet (not uploaded, or upload still catching up):`);
  missingList.slice(0, 20).forEach((f) => console.log('   -', f));
  if (missingList.length > 20) console.log(`   ... and ${missingList.length - 20} more`);
}

const out = [];
out.push('// Auto-generated by scripts/build-audio-urls.cjs (Trinity keys merged in by');
out.push('// scripts/merge-trinity-audio-urls.cjs) — do not edit by hand.');
out.push('// Every URL here was verified against a real GitHub Releases asset listing');
out.push('// (see the scripts for how) rather than assumed/pattern-generated.');
out.push(`window.AUDIO_URLS = ${JSON.stringify(audioMap, null, 2)};`);
fs.writeFileSync(OUT_FILE, out.join('\n') + '\n', 'utf-8');

const afterCount = Object.keys(audioMap).length;
console.log(`\nWrote ${afterCount} keys to ${OUT_FILE} (was ${beforeCount}, added ${afterCount - beforeCount}).`);
