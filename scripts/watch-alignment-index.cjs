// Lightweight watcher that periodically re-runs build-alignment-index.cjs's logic
// to keep app/alignment-data.js fresh as scripts/align-corpus.mjs (running separately,
// read-only from here) produces more data/alignment/**/*.json files over time.
//
// This script is READ-ONLY with respect to data/alignment/ and scripts/align-corpus.mjs.
// It only reads data/alignment/**/*.json and writes app/alignment-data.js.
//
// It does its own file scan on each tick (cheap: just fs.readdir + fs.readFileSync of
// small JSON files) and skips rewriting alignment-data.js unless the underlying data
// actually changed (tracked via a simple content signature: file count + total mtime).
// No ASR/transcription work happens here, and no shelling out to align-corpus.mjs.
//
// Usage: node scripts/watch-alignment-index.cjs [intervalMinutes]
//   intervalMinutes defaults to 3. Runs indefinitely until killed (Ctrl+C).

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ALIGN_DIR = path.join(ROOT, 'data', 'alignment');
const OUT_FILE = path.join(ROOT, 'app', 'alignment-data.js');

const INTERVAL_MINUTES = Number(process.argv[2]) > 0 ? Number(process.argv[2]) : 3;
const INTERVAL_MS = INTERVAL_MINUTES * 60 * 1000;

function findAlignmentFiles(dir) {
  var out = [];
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      out = out.concat(findAlignmentFiles(full));
    } else if (entry.isFile() && entry.name.endsWith('.json') && entry.name !== 'progress.json') {
      out.push(full);
    }
  }
  return out;
}

// Merge one question's articles into the index, keeping only matched: true entries.
function addQuestionArticles(index, part, question, articles, stats) {
  if (!articles || !articles.length) return;
  const key = 'P' + part + 'Q' + question;
  var bucket = index[key];
  articles.forEach(function (a) {
    if (!a || a.matched !== true || typeof a.approxStartSec !== 'number') return;
    if (!bucket) { bucket = {}; index[key] = bucket; }
    bucket['A' + a.articleNumber] = a.approxStartSec;
    stats.articlesIndexed++;
  });
  if (bucket && !stats.questionsSeen.has(key)) stats.questionsSeen.add(key);
}

// Compute a cheap signature of the current data/alignment/ contents (file count + sum of
// mtimes + sum of sizes) without reading any file bodies, so a no-change tick is nearly free.
function computeSignature(files) {
  var mtimeSum = 0;
  var sizeSum = 0;
  files.forEach(function (f) {
    try {
      const st = fs.statSync(f);
      mtimeSum += st.mtimeMs;
      sizeSum += st.size;
    } catch (e) {
      // File may have been removed/replaced mid-scan (align-corpus.mjs writing concurrently) — ignore.
    }
  });
  return files.length + ':' + Math.round(mtimeSum) + ':' + sizeSum;
}

function buildIndex(files) {
  const index = {};
  const stats = { articlesIndexed: 0, questionsSeen: new Set(), filesRead: 0, filesSkipped: 0 };

  files.forEach(function (f) {
    var record;
    try {
      record = JSON.parse(fs.readFileSync(f, 'utf-8'));
    } catch (e) {
      // Skip unreadable/partially-written files silently (align-corpus.mjs may be writing
      // this file concurrently); it'll be picked up cleanly on a later tick.
      stats.filesSkipped++;
      return;
    }
    stats.filesRead++;

    if (record.question && record.articles) {
      addQuestionArticles(index, record.question.part, record.question.question, record.articles, stats);
    } else if (Array.isArray(record.questions)) {
      record.questions.forEach(function (q) {
        addQuestionArticles(index, q.part, q.question, q.articles, stats);
      });
    }
  });

  return { index, stats };
}

function writeIndex(index) {
  const out = [];
  out.push('// Auto-generated by scripts/build-alignment-index.cjs — do not edit by hand.');
  out.push('// Rebuild any time with: node scripts/build-alignment-index.cjs');
  out.push('// Partial by design: only covers whatever data/alignment/**/*.json files exist so far');
  out.push('// (the background alignment batch job is still filling these in over time).');
  out.push('window.SUMMA_ALIGNMENT = ' + JSON.stringify(index, null, 2) + ';');
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, out.join('\n') + '\n', 'utf-8');
}

let lastSignature = null;

function tick() {
  var files;
  try {
    files = findAlignmentFiles(ALIGN_DIR).sort();
  } catch (e) {
    console.error('[watch-alignment-index] scan failed: ' + e.message);
    return;
  }

  const signature = computeSignature(files);
  if (signature === lastSignature) {
    // Nothing changed since last tick — stay quiet.
    return;
  }

  const { index, stats } = buildIndex(files);
  writeIndex(index);
  lastSignature = signature;

  const ts = new Date().toISOString();
  console.log(
    '[' + ts + '] Refreshed alignment-data.js: ' +
    stats.questionsSeen.size + ' questions, ' +
    stats.articlesIndexed + ' matched articles' +
    ' (from ' + stats.filesRead + ' files' + (stats.filesSkipped ? ', ' + stats.filesSkipped + ' skipped' : '') + ')'
  );
}

console.log(
  '[watch-alignment-index] Starting. Watching ' + ALIGN_DIR + ' every ' + INTERVAL_MINUTES +
  ' minute(s). Writing ' + OUT_FILE + '. Read-only w.r.t. data/alignment/. Ctrl+C to stop.'
);

tick(); // initial refresh so alignment-data.js is fresh as soon as this starts
setInterval(tick, INTERVAL_MS);
