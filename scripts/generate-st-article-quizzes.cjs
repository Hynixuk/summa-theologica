#!/usr/bin/env node
/**
 * generate-st-article-quizzes.cjs
 *
 * Generates a 3-question quiz for every Summa Theologica article with Groq,
 * then builds app/data-st-quizzes.js (window.ST_ARTICLE_QUIZZES) from the
 * results.
 *
 * Resumable: results accumulate in data/quizzes/st-articles.json, keyed
 * "P{part}Q{question}:A{article}". Re-running skips articles already done, so
 * it can be run a little at a time as the daily rate limit allows.
 *
 * Usage:
 *   node scripts/generate-st-article-quizzes.cjs              generate missing, then build
 *   node scripts/generate-st-article-quizzes.cjs --limit 20   stop after 20 new articles
 *   node scripts/generate-st-article-quizzes.cjs --only P1Q75:A1,P1Q2:A3
 *   node scripts/generate-st-article-quizzes.cjs --models openai/gpt-oss-20b
 *   node scripts/generate-st-article-quizzes.cjs --build      rebuild the app file only
 *
 * Needs GROQ_API_KEY in the environment or in .env.local.
 *
 * Rate limits: Groq's free tier limits each MODEL separately (about 8K tokens
 * per minute and 200K tokens per day). The live Explain and AI-search features
 * use openai/gpt-oss-120b, so this job deliberately uses other models and
 * never touches that budget.
 */

const fs = require('fs');
const path = require('path');
const https = require('https');

const ROOT = path.join(__dirname, '..');
const DATA_JS = path.join(ROOT, 'app', 'data.js');
const RESULTS_FILE = path.join(ROOT, 'data', 'quizzes', 'st-articles.json');
const OUT_FILE = path.join(ROOT, 'app', 'data-st-quizzes.js');

// Per-model request options. Reasoning models spend completion tokens on
// hidden reasoning before any output, so keep reasoning low and leave room.
const MODEL_CONFIG = {
  'openai/gpt-oss-20b': { reasoning_effort: 'low' },
  'qwen/qwen3.6-27b': { reasoning_effort: 'none' },
  'qwen/qwen3.8-27b': { reasoning_effort: 'none' },
};
const DEFAULT_MODELS = Object.keys(MODEL_CONFIG);

const MAX_ATTEMPTS = 3;
const SAVE_EVERY = 5;

// ---------- args ----------

const args = process.argv.slice(2);
function argValue(name) {
  const i = args.indexOf(name);
  return i === -1 ? null : args[i + 1];
}
const BUILD_ONLY = args.includes('--build');
const LIMIT = argValue('--limit') ? parseInt(argValue('--limit'), 10) : Infinity;
const ONLY = argValue('--only') ? new Set(argValue('--only').split(',').map((s) => s.trim())) : null;
const MODELS = argValue('--models') ? argValue('--models').split(',').map((s) => s.trim()) : DEFAULT_MODELS;

// ---------- data ----------

function loadSumma() {
  global.window = {};
  eval(fs.readFileSync(DATA_JS, 'utf-8'));
  return global.window.SUMMA_TEXT;
}

function loadResults() {
  if (!fs.existsSync(RESULTS_FILE)) return {};
  return JSON.parse(fs.readFileSync(RESULTS_FILE, 'utf-8'));
}

function saveResults(results) {
  fs.mkdirSync(path.dirname(RESULTS_FILE), { recursive: true });
  const sorted = {};
  Object.keys(results).sort(compareKeys).forEach((k) => { sorted[k] = results[k]; });
  const tmp = RESULTS_FILE + '.tmp';
  fs.writeFileSync(tmp, JSON.stringify(sorted, null, 2) + '\n', 'utf-8');
  fs.renameSync(tmp, RESULTS_FILE);
}

function parseKey(k) {
  const m = /^P(\d+)Q(\d+):A(\d+)$/.exec(k);
  return m ? [+m[1], +m[2], +m[3]] : [0, 0, 0];
}
function compareKeys(a, b) {
  const x = parseKey(a), y = parseKey(b);
  return x[0] - y[0] || x[1] - y[1] || x[2] - y[2];
}

function buildAppFile(results) {
  const out = {};
  Object.keys(results).sort(compareKeys).forEach((k) => { out[k] = results[k].questions; });
  const js =
    '// Auto-generated by scripts/generate-st-article-quizzes.cjs — do not edit by hand.\n' +
    '// Source: data/quizzes/st-articles.json. One 3-question quiz per Summa Theologica article,\n' +
    '// keyed "P{part}Q{question}:A{article}".\n' +
    'window.ST_ARTICLE_QUIZZES = ' + JSON.stringify(out) + ';\n';
  fs.writeFileSync(OUT_FILE, js, 'utf-8');
  return Object.keys(out).length;
}

// ---------- prompt ----------

function trimTo(text, max) {
  if (text.length <= max) return text;
  const cut = text.slice(0, max);
  const sentence = cut.lastIndexOf('. ');
  if (sentence > max * 0.6) return cut.slice(0, sentence + 1);
  const space = cut.lastIndexOf(' ');
  return (space > 0 ? cut.slice(0, space) : cut) + '…';
}

// Groups each labelled paragraph with the unlabelled continuation paragraphs
// that follow it (an objection or the responsio often spans several).
function sections(article) {
  const out = [];
  article.paragraphs.forEach((p) => {
    if (p.label || !out.length) out.push({ label: p.label || '', text: p.text });
    else out[out.length - 1].text += ' ' + p.text;
  });
  return out;
}

function buildArticlePrompt(article) {
  const secs = sections(article);
  const objections = secs.filter((s) => /^Objection/i.test(s.label));
  const answer = secs.find((s) => /^I answer that/i.test(s.label));
  const replies = secs.filter((s) => /^Reply to Objection/i.test(s.label));

  let body = 'ARTICLE QUESTION: ' + article.title + '\n\n';
  if (answer) {
    if (objections.length) {
      body += 'OBJECTIONS (positions Aquinas goes on to REJECT):\n' +
        objections.map((s, i) => (i + 1) + '. ' + trimTo(s.text, 320)).join('\n') + '\n\n';
    }
    body += 'AQUINAS\'S OWN ANSWER ("I answer that"):\n' + trimTo(answer.text, 2800);
    // The replies are what Question 3 is about. Without them the model has to
    // guess how Aquinas answers an objection — the pilot showed it gets that
    // wrong, so they must be in the prompt.
    if (replies.length) {
      body += '\n\nHIS REPLIES TO THE OBJECTIONS:\n' +
        replies.map((s) => s.label.replace(/[.,:]\s*$/, '') + ': ' + trimTo(s.text, 320)).join('\n');
    }
  } else {
    // A handful of articles have no labelled responsio.
    body += 'TEXT:\n' + trimTo(secs.map((s) => (s.label ? s.label + ' ' : '') + s.text).join(' '), 3200);
  }

  return (
    'Write a short multiple-choice quiz on this article from Thomas Aquinas\'s Summa Theologiae, ' +
    'for readers who are not specialists.\n\n' + body + '\n\n' +
    'Rules:\n' +
    '- Exactly 3 questions about THIS article. Question 1: what Aquinas concludes about the article\'s ' +
    'question. Question 2: the main reason he gives. Question 3: how he answers ONE specific objection — ' +
    'say in plain words which objection it is, and base the correct option ONLY on his reply to that ' +
    'objection as given above; never guess what a reply says. If no replies are given, ask instead about ' +
    'another important point in his answer.\n' +
    '- Plain, everyday English. No scholastic jargon; if an idea is technical, say it in ordinary words.\n' +
    '- Each question has exactly 4 options, all different, one of them correct.\n' +
    '- The correct option must state what Aquinas actually holds. The objections state views he REJECTS, ' +
    'so an objection\'s view is never the correct option. Wrong options should be tempting misreadings ' +
    '(for example the objection\'s view, a reversal, or an overstatement) that a careful reader would ' +
    'still recognise as wrong.\n' +
    '- Every wrong option must be clearly false according to the text above: never something Aquinas ' +
    'also accepts, and never merely a vaguer version of the correct option.\n' +
    '- Never use options like "All of the above", "None of the above", "The article does not say", ' +
    '"Further inquiry is needed" or "It is partially accepted".\n' +
    '- Keep every option under 25 words. Make the wrong options just as specific and detailed as the ' +
    'correct one, so length gives nothing away: across the three questions the correct option should ' +
    'be the shortest or a middle length about as often as it is the longest.\n' +
    '- Paraphrase; do not copy long phrases from the text.\n' +
    '- "explanation": one or two plain sentences saying why the correct option is right.\n\n' +
    'Respond with JSON only, in exactly this shape:\n' +
    '{"questions":[{"q":"...","options":["...","...","...","..."],"correct":0,"explanation":"..."}]}'
  );
}

// ---------- validation ----------

const BANNED_OPTION = /all of the above|none of the above|does not (say|address|provide|state)|further inquiry|partially accepted|is ambiguous|not enough information/i;

function normalise(s) {
  return String(s).trim().replace(/\s+/g, ' ');
}

// Returns { questions } on success or { error } describing the first problem.
function validate(raw) {
  let parsed;
  try { parsed = JSON.parse(raw); } catch (e) { return { error: 'invalid JSON' }; }
  const qs = parsed && parsed.questions;
  if (!Array.isArray(qs) || qs.length !== 3) return { error: 'expected exactly 3 questions' };

  const seenQ = new Set();
  const clean = [];
  for (let i = 0; i < qs.length; i++) {
    const item = qs[i] || {};
    const q = normalise(item.q || '');
    const explanation = normalise(item.explanation || '');
    const options = Array.isArray(item.options) ? item.options.map(normalise) : [];
    const correct = item.correct;

    if (q.length < 10 || q.length > 300) return { error: 'q' + (i + 1) + ': bad question length' };
    if (/\?\?/.test(q)) return { error: 'q' + (i + 1) + ': doubled question mark' };
    if (seenQ.has(q.toLowerCase())) return { error: 'q' + (i + 1) + ': duplicate question' };
    seenQ.add(q.toLowerCase());
    if (options.length !== 4) return { error: 'q' + (i + 1) + ': expected 4 options' };
    if (options.some((o) => o.length < 2 || o.length > 220)) return { error: 'q' + (i + 1) + ': bad option length' };
    if (new Set(options.map((o) => o.toLowerCase())).size !== 4) return { error: 'q' + (i + 1) + ': duplicate options' };
    if (options.some((o) => BANNED_OPTION.test(o))) return { error: 'q' + (i + 1) + ': filler option' };
    if (!Number.isInteger(correct) || correct < 0 || correct > 3) return { error: 'q' + (i + 1) + ': bad correct index' };
    if (explanation.length < 10 || explanation.length > 600) return { error: 'q' + (i + 1) + ': bad explanation' };

    // Guessability: reject a correct option that is conspicuously the longest.
    // 1.25x catches the obvious cases; a stricter bar regenerated about a third
    // of pilot sets, which the daily token budget can't afford.
    const others = options.filter((_, j) => j !== correct).map((o) => o.length);
    if (options[correct].length > 1.25 * Math.max.apply(null, others)) {
      return { error: 'q' + (i + 1) + ': correct option is conspicuously longest' };
    }

    clean.push({ q, options, correct, explanation });
  }
  return { questions: clean };
}

// Shuffle options so the correct answer's position carries no signal.
function shuffleOptions(item) {
  const order = [0, 1, 2, 3];
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const t = order[i]; order[i] = order[j]; order[j] = t;
  }
  return {
    q: item.q,
    options: order.map((i) => item.options[i]),
    correct: order.indexOf(item.correct),
    explanation: item.explanation,
  };
}

// ---------- Groq ----------

function readApiKey() {
  if (process.env.GROQ_API_KEY) return process.env.GROQ_API_KEY.trim();
  const envFile = path.join(ROOT, '.env.local');
  if (fs.existsSync(envFile)) {
    const m = fs.readFileSync(envFile, 'utf-8').match(/^\s*GROQ_API_KEY\s*=\s*(.+)\s*$/m);
    if (m) return m[1].trim().replace(/^["']|["']$/g, '');
  }
  throw new Error('GROQ_API_KEY not found in the environment or .env.local');
}

function callGroq(model, prompt, apiKey) {
  const body = JSON.stringify(Object.assign({
    model,
    messages: [{ role: 'user', content: prompt }],
    temperature: 0.4,
    max_tokens: 2500,
    response_format: { type: 'json_object' },
  }, MODEL_CONFIG[model] || {}));

  return new Promise((resolve) => {
    const req = https.request({
      hostname: 'api.groq.com',
      path: '/openai/v1/chat/completions',
      method: 'POST',
      headers: {
        Authorization: 'Bearer ' + apiKey,
        'Content-Type': 'application/json',
        'Content-Length': Buffer.byteLength(body), // bytes, not characters
      },
    }, (res) => {
      let data = '';
      res.on('data', (c) => { data += c; });
      res.on('end', () => {
        let json = null;
        try { json = JSON.parse(data); } catch (e) { /* handled below */ }
        resolve({ status: res.statusCode, headers: res.headers, json, raw: data });
      });
    });
    req.on('error', (e) => resolve({ status: 0, headers: {}, json: null, raw: e.message }));
    req.setTimeout(120000, () => req.destroy(new Error('timeout')));
    req.write(body);
    req.end();
  });
}

// Groq reset headers look like "7.66s", "2m59.56s" or "1h2m3s".
function parseDuration(s) {
  if (!s) return 0;
  let total = 0;
  const re = /([\d.]+)(ms|h|m|s)/g;
  let m;
  while ((m = re.exec(String(s)))) {
    const v = parseFloat(m[1]);
    total += m[2] === 'h' ? v * 3600 : m[2] === 'm' ? v * 60 : m[2] === 'ms' ? v / 1000 : v;
  }
  return total;
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// ---------- main ----------

async function main() {
  const results = loadResults();

  if (BUILD_ONLY) {
    const n = buildAppFile(results);
    console.log('Built ' + path.relative(ROOT, OUT_FILE) + ' with ' + n + ' article quizzes.');
    return;
  }

  const apiKey = readApiKey();
  const summa = loadSumma();

  const queue = [];
  Object.keys(summa).forEach((qk) => {
    summa[qk].articles.forEach((a) => {
      const key = qk + ':A' + a.number;
      if (ONLY && !ONLY.has(key)) return;
      // --force regenerates finished articles, but only together with --only,
      // so a stray flag can't burn the whole daily budget redoing everything.
      if (results[key] && !(ONLY && args.includes('--force'))) return;
      queue.push({ key, article: a });
    });
  });
  queue.sort((x, y) => compareKeys(x.key, y.key));

  const total = Object.values(summa).reduce((n, q) => n + q.articles.length, 0);
  console.log('Articles: ' + total + ' | done: ' + Object.keys(results).length + ' | to do: ' + queue.length);
  if (!queue.length) { buildAppFile(results); return; }

  let taken = 0;
  let unsaved = 0;
  const stats = { ok: 0, failed: 0, retries: 0, promptTokens: 0, completionTokens: 0 };
  const rejects = {};
  let stopping = false;

  function persist() {
    if (!unsaved) return;
    saveResults(results);
    unsaved = 0;
  }
  process.on('SIGINT', () => {
    console.log('\nInterrupted — saving progress…');
    stopping = true;
    persist();
    buildAppFile(results);
    process.exit(130);
  });

  async function worker(model) {
    while (!stopping) {
      if (taken >= LIMIT) return;
      const job = queue.shift();
      if (!job) return;
      taken++;

      const prompt = buildArticlePrompt(job.article);
      let done = false;

      for (let attempt = 1; attempt <= MAX_ATTEMPTS && !done && !stopping; attempt++) {
        const res = await callGroq(model, prompt, apiKey);

        if (res.status === 429) {
          const wait = parseFloat(res.headers['retry-after']) || 20;
          const msg = (res.json && res.json.error && res.json.error.message) || '';
          if (wait > 600 || /per day|TPD|RPD/i.test(msg)) {
            console.log('[' + model + '] daily limit reached — this model stops for today.');
            queue.unshift(job); taken--;
            return;
          }
          await sleep(wait * 1000 + 250);
          attempt--; // a rate-limit wait isn't a failed attempt
          continue;
        }

        if (res.status !== 200 || !res.json) {
          const msg = (res.json && res.json.error && res.json.error.message) || res.raw.slice(0, 200);
          console.log('[' + model + '] ' + job.key + ' HTTP ' + res.status + ': ' + msg);
          if (res.status === 400 || res.status === 404) {
            // Bad request for this model (e.g. an unsupported parameter) — don't keep retrying it.
            queue.unshift(job); taken--;
            return;
          }
          await sleep(3000);
          continue;
        }

        const usage = res.json.usage || {};
        stats.promptTokens += usage.prompt_tokens || 0;
        stats.completionTokens += usage.completion_tokens || 0;

        const content = res.json.choices && res.json.choices[0] && res.json.choices[0].message &&
          res.json.choices[0].message.content;
        const v = validate(content || '');
        if (v.error) {
          rejects[v.error.replace(/^q\d+: /, '')] = (rejects[v.error.replace(/^q\d+: /, '')] || 0) + 1;
          stats.retries++;
          continue;
        }

        results[job.key] = {
          model,
          generatedAt: new Date().toISOString(),
          questions: v.questions.map(shuffleOptions),
        };
        stats.ok++;
        done = true;
        if (++unsaved >= SAVE_EVERY) persist();
        if (stats.ok % 25 === 0) {
          console.log('  ' + stats.ok + ' generated (' + Object.keys(results).length + '/' + total + ' total)');
        }

        // Pace against the per-minute token budget reported by Groq.
        const remaining = parseInt(res.headers['x-ratelimit-remaining-tokens'], 10);
        if (!isNaN(remaining) && remaining < 3000) {
          await sleep(parseDuration(res.headers['x-ratelimit-reset-tokens']) * 1000 + 250);
        }
      }

      if (!done && !stopping) {
        stats.failed++;
        console.log('[' + model + '] ' + job.key + ' failed after ' + MAX_ATTEMPTS + ' attempts; skipped.');
      }
    }
  }

  await Promise.all(MODELS.map(worker));
  persist();
  const built = buildAppFile(results);

  const n = stats.ok || 1;
  console.log('\nGenerated: ' + stats.ok + ' | failed: ' + stats.failed + ' | validation retries: ' + stats.retries);
  console.log('Tokens: ' + stats.promptTokens + ' prompt + ' + stats.completionTokens + ' completion ' +
    '(~' + Math.round((stats.promptTokens + stats.completionTokens) / n) + ' per article)');
  if (Object.keys(rejects).length) console.log('Rejected outputs by reason: ' + JSON.stringify(rejects));
  console.log('Progress: ' + built + '/' + total + ' articles. Built ' + path.relative(ROOT, OUT_FILE) + '.');
  if (built < total) console.log('Run again later to continue — finished articles are skipped.');
}

main().catch((e) => { console.error(e); process.exit(1); });
