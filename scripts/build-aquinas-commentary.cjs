#!/usr/bin/env node
// Merges data/aquinas-commentary/book*.json (one file per Metaphysics book,
// each an array of {book, chapter, commentary}, written by per-book generation
// agents) into app/data-aquinas-commentary.js, keyed "B{book}C{chapter}".
//
// Skips files starting with "_" (the _source-bookN.json reference files used
// by the generation agents — not commentary output).
//
// Usage: node scripts/build-aquinas-commentary.cjs

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'data', 'aquinas-commentary');
const OUT_FILE = path.join(ROOT, 'app', 'data-aquinas-commentary.js');

function build() {
  const index = {};
  const perBook = [];

  if (!fs.existsSync(SRC_DIR)) {
    return { index, perBook };
  }

  const files = fs.readdirSync(SRC_DIR)
    .filter((f) => f.endsWith('.json') && !f.startsWith('_'))
    .sort();

  for (const f of files) {
    let entries;
    try {
      entries = JSON.parse(fs.readFileSync(path.join(SRC_DIR, f), 'utf-8'));
    } catch (e) {
      console.warn(`  Skipping ${f} (unreadable/mid-write): ${e.message}`);
      continue;
    }
    if (!Array.isArray(entries)) continue;
    let count = 0;
    for (const e of entries) {
      if (!e || typeof e.book !== 'number' || typeof e.chapter !== 'number' || !e.commentary) continue;
      index[`B${e.book}C${e.chapter}`] = e.commentary;
      count++;
    }
    if (count > 0) perBook.push({ file: f, count });
  }

  return { index, perBook };
}

function writeData(index) {
  const out = [];
  out.push('// Auto-generated by scripts/build-aquinas-commentary.cjs (kept fresh by scripts/watch-aquinas-commentary.cjs) — do not edit by hand.');
  out.push('// Paraphrased summaries of St. Thomas Aquinas\'s Sententia libri Metaphysicae, one per Metaphysics chapter.');
  out.push('// Original wording based on the public-domain Latin text (corpusthomisticum.org) — not a translation of any modern copyrighted edition.');
  out.push(`window.AQUINAS_COMMENTARY = ${JSON.stringify(index, null, 2)};`);
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, out.join('\n') + '\n', 'utf-8');
}

function main() {
  const { index, perBook } = build();
  writeData(index);
  const total = Object.keys(index).length;
  console.log(`Wrote ${OUT_FILE}`);
  console.log(`  Total chapters with commentary: ${total}`);
  perBook.forEach((b) => console.log(`  ${b.file}: ${b.count} chapters`));
}

main();
